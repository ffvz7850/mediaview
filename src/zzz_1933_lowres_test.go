package main

import "testing"

// TestLowresForFormula 守住 -lowres 档位公式。
//
// 档位必须按目标尺寸动态算：取小了没收益，取大了会把源图缩到比目标还小、
// 后面接 scale 就成了「放大糊掉」。实测（8736x11648 → 1920 档）：
//
//	  正确档 N=2 → 输出 305479 B；过高档 N=3 → 只有 269918 B（细节已丢）。
//
//		公式：N = clamp(floor(log2(长边/目标)), 0, 3)
func TestLowresForFormula(t *testing.T) {
	cases := []struct {
		w, h, target, want int
		desc               string
	}{
		// 102MP 渐进式巨图（实测样本 8736x11648）
		{8736, 11648, 320, 3, "102MP → 320：11648/8=1456 ≥ 320"},
		{8736, 11648, 1920, 2, "102MP → 1920：11648/4=2912 ≥ 1920（N=3 会糊）"},
		// 普通 6000x4000
		{6000, 4000, 320, 3, "24MP → 320：6000/8=750 ≥ 320"},
		{6000, 4000, 1920, 1, "24MP → 1920：6000/2=3000 ≥ 1920（N=2 只剩 1500 → 会糊）"},
		// 边界
		{1920, 1080, 1920, 0, "源图不比目标大 → 不启用"},
		{3840, 2160, 1920, 1, "正好 2 倍"},
		{800, 600, 320, 1, "小图 800/2=400 ≥ 320"},
		{640, 480, 320, 1, "640/2=320 ≥ 320（等号也算够）"},
		// minRatio=0.9 之后：300 >= 320*0.9=288 → 仍启用（输出 300，缩 6%，在允许范围内）
		{600, 400, 320, 1, "600/2=300 >= 320*0.9 → 启用 N=1"},
		{100000, 100000, 320, 3, "极端大图被钳到上限 3"},
		// minRatio=0.9 的核心效果（原图 8736x11648，实测 N=2 比 N=1 快 39%，
		// 而输出 2912 仍高于实际视口 2160）：3072 切 N=2；4096 因会明显缩水仍 N=1
		{8736, 11648, 3072, 2, "11648/4=2912 >= 3072*0.9=2765 → N=2（快 39%，缩小 5%）"},
		{8736, 11648, 3584, 1, "11648/4=2912 < 3584*0.9=3226 → 仍 N=1（不缩水）"},
		{8736, 11648, 4096, 1, "11648/4=2912 < 4096*0.9=3687 → 仍 N=1"},
		{0, 0, 320, 0, "未知尺寸 → 不启用"},
		{4000, 6000, 320, 3, "竖图按长边（h）算"},
	}
	for _, c := range cases {
		if got := lowresFor(c.w, c.h, c.target); got != c.want {
			t.Errorf("lowresFor(%d,%d,%d) = %d，期望 %d（%s）",
				c.w, c.h, c.target, got, c.want, c.desc)
		}
	}
	// 上限必须是 3（ffmpeg 实测 4/9 被钳制到 3）
	if got := lowresFor(1000000, 1000000, 320); got > 3 {
		t.Errorf("档位 %d 超过 ffmpeg 上限 3", got)
	}
}
